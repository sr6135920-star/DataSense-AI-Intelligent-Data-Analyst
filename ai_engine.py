"""
ai_engine.py
============
AI integration module for DataSense AI.
Uses the official google-genai SDK to generate automated insights and
powers an interactive conversational data analyst chat.

All prompt engineering incorporates real, verified Pandas calculation results
so the AI explains authentic data rather than hallucinating metrics.
"""

import os
from typing import List, Dict, Optional, Tuple
from dotenv import load_dotenv

# Load environment variables from .env file
load_dotenv()


def get_api_key(provided_key: Optional[str] = None) -> Optional[str]:
    """
    Retrieves the Gemini API key.
    Checks user-provided key first, then falls back to .env / os environment.
    """
    if provided_key and provided_key.strip():
        return provided_key.strip()
    return os.getenv("GEMINI_API_KEY", "").strip() or None


def _call_gemini_api(prompt: str, api_key: str) -> Tuple[Optional[str], Optional[str]]:
    """
    Internal helper to call the Gemini API using the official google-genai SDK.
    Includes a fallback for google-generativeai to ensure maximum compatibility.
    """
    # 1. Primary path: Official google-genai SDK
    try:
        from google import genai
        from google.genai import types

        client = genai.Client(api_key=api_key)
        
        # Active Gemini models in order of speed and stability
        model_names = [
            "gemini-3.5-flash-lite",
            "gemini-3.5-flash",
            "gemini-3.8-flash",
        ]
        last_error = None

        for model_name in model_names:
            try:
                response = client.models.generate_content(
                    model=model_name,
                    contents=prompt,
                )
                if response and response.text:
                    return response.text, None
            except Exception as e:
                last_error = str(e)
                continue

        if last_error:
            return None, f"Gemini API request failed: {last_error}"

    except ImportError:
        # 2. Fallback: Legacy google-generativeai SDK if installed
        try:
            import google.generativeai as legacy_genai

            legacy_genai.configure(api_key=api_key)
            model_names = ["gemini-1.5-flash", "gemini-1.5-pro", "gemini-pro"]
            last_error = None

            for m in model_names:
                try:
                    model = legacy_genai.GenerativeModel(m)
                    response = model.generate_content(prompt)
                    if response and response.text:
                        return response.text, None
                except Exception as e:
                    last_error = str(e)
                    continue

            return None, f"Gemini API error: {last_error}"
        except ImportError:
            return None, "Neither 'google-genai' nor 'google-generativeai' is installed. Please run: pip install google-genai"

    except Exception as general_err:
        return None, f"An unexpected error occurred while contacting Gemini API: {str(general_err)}"

    return None, "No response generated by Gemini model."


def generate_executive_insights(data_context: str, api_key: str) -> Tuple[Optional[str], Optional[str]]:
    """
    Generates a structured executive summary and analytical insights
    based strictly on the real Pandas calculation results provided in data_context.
    """
    prompt = f"""You are 'DataSense AI', a professional Senior Data Analyst.
Analyze the following dataset facts and statistical calculations computed by Pandas.

{data_context}

INSTRUCTIONS:
1. Provide a clean, professional, executive-level summary formatted in Markdown.
2. Structure your response into these 4 distinct sections:
   - 📌 **Executive Overview**: High-level dataset summary (scale, health, and primary scope).
   - 🔍 **Key Findings & Trends**: Notable averages, distributions, spreads, and high-value metrics.
   - ⚠️ **Data Quality & Anomalies**: Observations on missing values, duplicates, outliers, or skewness.
   - 💡 **Actionable Business Recommendations**: Practical, concrete business steps based on these metrics.
3. Strict Grounding: Rely ONLY on the numbers and columns explicitly listed in the facts above.
4. Do not invent any numbers, percentages, or columns not present in the context.
"""
    return _call_gemini_api(prompt, api_key)


def answer_data_query(
    user_query: str,
    chat_history: List[Dict[str, str]],
    data_context: str,
    api_key: str
) -> Tuple[Optional[str], Optional[str]]:
    """
    Answers a specific user question about the uploaded dataset using real Pandas stats.
    Includes previous conversational context for natural multi-turn chat.
    """
    # Format the recent chat history
    history_lines = []
    for msg in chat_history[-6:]:  # Keep recent turns to fit within context neatly
        role = "User" if msg["role"] == "user" else "DataSense AI"
        history_lines.append(f"{role}: {msg['content']}")
    history_text = "\n".join(history_lines) if history_lines else "None"

    prompt = f"""You are 'DataSense AI', an intelligent data analyst chatbot.
You are helping a user explore and understand their uploaded dataset.

=== DATASET FACTS & STATISTICAL METRICS (COMPUTED BY PANDAS) ===
{data_context}

=== RECENT CHAT HISTORY ===
{history_text}

=== USER QUESTION ===
{user_query}

GUIDELINES:
1. Answer the question directly, concisely, and professionally using the dataset facts above.
2. Quote exact numbers from the metrics table when relevant (e.g., mean, maximum, counts).
3. If the answer cannot be determined from the available columns or summary, politely explain that the dataset does not contain the necessary information.
4. Never make up statistics. Use bullet points and bold formatting for clarity.
"""
    return _call_gemini_api(prompt, api_key)
